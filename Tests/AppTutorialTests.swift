import Foundation

@main
struct AppTutorialTests {
    static func main() {
        var tutorial = AppTutorial()
        tutorial.start(hasEvents: true, categoryID: "existing-category", pinEventID: "existing-event")
        precondition(tutorial.step == .finishEvent)
        tutorial.next()
        precondition(tutorial.step == .finishEvent, "Next cannot bypass finishing an event")
        tutorial.openedTab("view")
        precondition(tutorial.step == .finishEvent)
        tutorial.finishedEvent(completionID: "practice-completion")
        precondition(tutorial.step == .planAdd, "Explain Plan Add immediately after finishing the practice event")
        precondition(!AppTutorial.Step.planAdd.requiresInteraction, "Plan Add is explained without creating a record")
        precondition(tutorial.completionID == "practice-completion")
        tutorial.next()
        precondition(tutorial.step == .completedTab)
        tutorial.openedTab("view")
        precondition(tutorial.step == .shareDay)
        precondition(!AppTutorial.Step.shareDay.requiresInteraction, "Sharing is explained without requiring a message to be sent")
        tutorial.deletedCompletion(id: "practice-completion")
        precondition(tutorial.step == .shareDay, "Keep the practice completion until after the sharing explanation")
        tutorial.next()
        precondition(tutorial.step == .deleteCompletion)
        tutorial.next()
        precondition(tutorial.step == .deleteCompletion, "Next cannot bypass deleting the completion")
        tutorial.deletedCompletion(id: "unrelated-completion")
        precondition(tutorial.step == .deleteCompletion)
        tutorial.deletedCompletion(id: "practice-completion")
        precondition(tutorial.step == .libraryTab)
        tutorial.openedTab("library")
        precondition(tutorial.step == .categoryPlus)
        tutorial.next()
        precondition(tutorial.step == .openCategory && tutorial.categoryID == "existing-category")
        tutorial.next()
        precondition(tutorial.step == .createEvent)
        tutorial.next()
        precondition(tutorial.step == .statisticsTab, "Creation explanations must not require a save")
        tutorial.openedTab("statistic")
        precondition(tutorial.step == .pinEvent && tutorial.pinEventID == "existing-event")
        tutorial.next()
        precondition(tutorial.step == .unpinEvent)
        tutorial.next()
        precondition(tutorial.step == .statistics)
        tutorial.finish()
        precondition(!tutorial.isActive && tutorial.completionID == nil)
        precondition(tutorial.categoryID == nil && tutorial.pinEventID == nil)
        for step in AppTutorial.Step.allCases {
            tutorial.step = step
            tutorial.finish()
            precondition(!tutorial.isActive)
        }
        tutorial.start(hasEvents: false)
        precondition(tutorial.step == .planAdd, "Empty libraries should still learn about one-time plans")
        tutorial.next()
        precondition(tutorial.step == .libraryTab)
        print("App tutorial mixed interaction checks passed")
    }
}
